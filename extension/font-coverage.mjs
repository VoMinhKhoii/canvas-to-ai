// Writes src/pack/font-coverage.js: the characters pdfmake's Roboto can draw
// in all four of its styles, as code point ranges. Run after upgrading
// pdfmake (`npm run fonts`); a test checks the file still matches the font.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const fontkit = require('fontkit');
const vfs = require('pdfmake/build/vfs_fonts.js');

export function coverage() {
  const sets = Object.values(vfs).map((data) => new Set(fontkit.create(Buffer.from(data, 'base64')).characterSet));
  const ranges = [];
  for (const c of [...sets[0]].filter((c) => sets.every((s) => s.has(c))).sort((a, b) => a - b)) {
    const last = ranges.at(-1);
    if (last && last[1] === c - 1) last[1] = c;
    else ranges.push([c, c]);
  }
  return ranges;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync('src/pack/font-coverage.js', `// Generated by font-coverage.mjs from pdfmake's Roboto: do not edit.
// The code points every style of the PDF pages' font can draw, as [first, last] ranges.
export const COVERED = ${JSON.stringify(coverage())};
`);
}
